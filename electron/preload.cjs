const { contextBridge, ipcRenderer } = require('electron');
// toglie il prefisso tecnico di Electron dai messaggi d'errore
const call = (ch) => (...a) => ipcRenderer.invoke(ch, ...a).catch((e) => { throw new Error(String(e && e.message || e).replace(/^Error invoking remote method '[^']*': (Error: )?/, '')); });
contextBridge.exposeInMainWorld('bibo', {
  platform: process.platform,
  sysInfo: call('sys:info'),
  scanJunk: call('junk:scan'),
  cleanJunk: call('junk:clean'),
  startupList: call('startup:list'),
  setTheme: call('theme:set'),
  startupSettings: call('startup:settings'),
  startupSet: call('startup:set'),
  protection: call('protection:get'),
  programs: call('programs:list'),
  removeProgram: call('programs:remove'),
  largeScan: call('large:scan'),
  largeTrash: call('large:trash'),
  dupScan: call('dup:scan'),
  dupTrash: call('dup:trash'),
  prefsGet: call('prefs:get'),
  prefsSet: call('prefs:set'),
  privacyScan: call('privacy:scan'),
  blockersGet: call('blockers:get'),
  blockersTerminate: call('blockers:terminate'),
  privacyClean: call('privacy:clean'),
  protectionScan: call('protection:scan'),
  diskUsage: call('disk:usage'),
  diskFolder: call('disk:folder'),
  getUiVersion: call('ui:version:get'),
  setUiVersion: call('ui:version:set'),
  updatesList: call('updates:list'),
  updatesApply: call('updates:apply'),
  restoreCreate: call('restore:create'),
  memoryFree: call('memory:free'),
  leftovers: call('programs:leftovers'),
  leftoversTrash: call('programs:leftovers:trash'),
  registryDelete: call('programs:registry:delete'),
  memoryApps: call('memory:apps'),
  memoryClose: call('memory:close'),
  appInfo: call('app:info'),
  setKeepInTray: call('app:keep'),
  testNotification: call('app:notify'),
  quit: call('app:quit'),
  // la finestra può essere portata su una sezione dal tasto destro sull'icona nella barra
  onNav: (cb) => { const h = (_e, id) => cb(id); ipcRenderer.on('nav', h); return () => ipcRenderer.removeListener('nav', h); },
});
